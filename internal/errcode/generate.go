package errcode

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"
)

const generatedHeader = "// Code generated by errcodegen; DO NOT EDIT.\n\n"

// GenerateGo 生成 internal/errcode/codes_gen.go。
func GenerateGo(codes []Code) ([]byte, error) {
	if err := ValidateAll(codes); err != nil {
		return nil, err
	}
	sorted := append([]Code(nil), codes...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Code < sorted[j].Code })

	var buf bytes.Buffer
	buf.WriteString(generatedHeader)
	buf.WriteString("package errcode\n\n")
	buf.WriteString("const (\n")
	for _, c := range sorted {
		fmt.Fprintf(&buf, "\t%s = %q\n", c.Code, c.Code)
	}
	buf.WriteString(")\n\n")
	buf.WriteString("var HTTPStatus = map[string]int{\n")
	for _, c := range sorted {
		fmt.Fprintf(&buf, "\t%q: %d,\n", c.Code, c.HTTP)
	}
	buf.WriteString("}\n\n")
	buf.WriteString("var I18nKey = map[string]string{\n")
	for _, c := range sorted {
		fmt.Fprintf(&buf, "\t%q: %q,\n", c.Code, c.I18n)
	}
	buf.WriteString("}\n")
	return buf.Bytes(), nil
}

// GenerateTS 生成 packages/api-client/src/generated/error-codes.ts。
func GenerateTS(codes []Code) ([]byte, error) {
	if err := ValidateAll(codes); err != nil {
		return nil, err
	}
	sorted := append([]Code(nil), codes...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Code < sorted[j].Code })

	var buf bytes.Buffer
	buf.WriteString(generatedHeader)
	buf.WriteString("export const ERROR_CODES = {\n")
	for _, c := range sorted {
		fmt.Fprintf(&buf, "  %s: %q,\n", c.Code, c.Code)
	}
	buf.WriteString("} as const;\n\n")
	buf.WriteString("export type ErrorCode = (typeof ERROR_CODES)[keyof typeof ERROR_CODES];\n\n")
	buf.WriteString("export const ERROR_HTTP_STATUS: Record<ErrorCode, number> = {\n")
	for _, c := range sorted {
		fmt.Fprintf(&buf, "  %s: %d,\n", c.Code, c.HTTP)
	}
	buf.WriteString("};\n\n")
	buf.WriteString("export const ERROR_I18N_KEYS: Record<ErrorCode, string> = {\n")
	for _, c := range sorted {
		fmt.Fprintf(&buf, "  %s: %q,\n", c.Code, c.I18n)
	}
	buf.WriteString("};\n")
	return buf.Bytes(), nil
}

// GenerateMessages 生成 messages/errors.<locale>.json；locale 仅支持 zh-CN / en-US。
func GenerateMessages(codes []Code, locale string) ([]byte, error) {
	if err := ValidateAll(codes); err != nil {
		return nil, err
	}
	messages := make(map[string]string, len(codes))
	for _, c := range codes {
		switch locale {
		case "zh-CN":
			messages[c.Code] = c.Message
		case "en-US":
			if c.MessageEn != "" {
				messages[c.Code] = c.MessageEn
			} else {
				messages[c.Code] = c.Code
			}
		default:
			return nil, fmt.Errorf("unsupported locale %q", locale)
		}
	}
	out, err := json.MarshalIndent(messages, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(out, '\n'), nil
}

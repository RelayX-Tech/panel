package model

import (
	"os"
	"strings"
	"testing"

	"github.com/zeromicro/go-zero/core/stores/cache"
	"github.com/zeromicro/go-zero/core/stores/sqlx"
)

// 生成物文件名（design.md §5.1.1）。
var generatedModelFiles = []string{
	"authusersmodel.go",
	"authusersmodel_gen.go",
	"authsessionsmodel.go",
	"authsessionsmodel_gen.go",
	"authpasswordauditsmodel.go",
	"authpasswordauditsmodel_gen.go",
	"vars.go",
}

// TestGeneratedModelsCommitted 确保 goctl 生成物存在且已入库、未被手改（AC1 / TC-BE-002）。
func TestGeneratedModelsCommitted(t *testing.T) {
	for _, name := range generatedModelFiles {
		data, err := os.ReadFile(name)
		if err != nil {
			t.Errorf("generated model %s missing: %v", name, err)
			continue
		}
		if name == "vars.go" {
			if !strings.Contains(string(data), "ErrNotFound") {
				t.Errorf("%s does not define ErrNotFound", name)
			}
			continue
		}
		// goctl 1.10.2 仅在 *_gen.go 写入生成头；*model.go 是可扩展包装文件（同样由 goctl 生成）。
		if strings.HasSuffix(name, "_gen.go") && !strings.Contains(string(data), "Code generated by goctl. DO NOT EDIT.") {
			t.Errorf("%s is not a goctl generated file (or was hand-edited)", name)
		}
	}
}

// 生成 constructor 的签名是适配层的编译期契约（design.md §5.1.3）。
var (
	_ func(sqlx.SqlConn, cache.CacheConf, ...cache.Option) AuthUsersModel    = NewAuthUsersModel
	_ func(sqlx.SqlConn, cache.CacheConf, ...cache.Option) AuthSessionsModel = NewAuthSessionsModel
	_ func(sqlx.SqlConn) AuthPasswordAuditsModel                             = NewAuthPasswordAuditsModel
)

// TestGeneratedModelFields 确保生成类型覆盖领域字段（uuid / bytea / timestamptz）。
func TestGeneratedModelFields(t *testing.T) {
	u := AuthUsers{Id: "id", Account: "a", PasswordHash: "h", DisplayName: "d"}
	if u.Id == "" || u.Account != "a" {
		t.Errorf("AuthUsers = %+v", u)
	}
	s := AuthSessions{Id: "id", SessionHash: "hash", UserId: "uid"}
	if s.Id == "" || s.SessionHash != "hash" || s.UserId != "uid" {
		t.Errorf("AuthSessions = %+v", s)
	}
	a := AuthPasswordAudits{Id: "id", UserId: "uid", RequestId: "rid", Result: "success"}
	if a.Id == "" || a.UserId != "uid" || a.RequestId != "rid" || a.Result != "success" {
		t.Errorf("AuthPasswordAudits = %+v", a)
	}
}
